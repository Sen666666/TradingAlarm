"""Audit every saved synthetic receipt with the independent source ledger.

Reads outputs already generated by the formal runner; never executes the model.
"""
import json
from datetime import datetime, timezone
import pandas as pd
from audit import ROOT, audit_saved, load_model, digest, save


def main():
    model = load_model()
    validation = ROOT / 'validation'
    files = sorted(validation.glob('*.parquet'))
    files += sorted((validation/'transforms').glob('*.parquet'))
    files += sorted((validation/'probes').glob('*.parquet'))
    findings = []
    for path in files:
        saved = pd.read_parquet(path)
        source = saved[model.INPUT_COLUMNS]
        event_path = path.with_name(path.stem+'-events.json')
        events = json.loads(event_path.read_text())
        counts = audit_saved(source, saved, events, model)
        findings.append(dict(path=str(path.relative_to(ROOT)), **counts,
                             saved_sha256=digest(path), journal_sha256=digest(event_path)))
    report = dict(recorded_at=datetime.now(timezone.utc).isoformat(), passed=True,
                  total_saved_paths=len(files), paths=findings,
                  independent_audit_sha256=digest(ROOT/'reviews/audit/audit.py'),
                  launcher_sha256=digest(__file__), model_sha256=digest(ROOT/'code/model.py'),
                  production_model_runs=0, account_runs=0)
    save(ROOT/'reviews/audit/validation-audit.json', report)
    print(json.dumps(dict(passed=True, paths=len(files),
                         independent_rows=sum(x['independent_rows'] for x in findings),
                         all_confirmation_receipts=sum(x['all_confirmation_receipts'] for x in findings),
                         upward_confirmation_receipts=sum(x['upward_confirmation_receipts'] for x in findings)),
                     ensure_ascii=False))


if __name__ == '__main__':
    main()
