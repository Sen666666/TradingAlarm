def metric(cid,p):
 r=f.loc[f.case.eq(cid)&f.policy.eq(p)&f.scenario.eq('base')].iloc[0]
 return f'{r.net_return*100:+.2f}% / {r.max_drawdown*100:.2f}%'

def mean_table(role,policies):
 rows=['|规则|收益均值|回撤均值|自然退出交易胜率|零交易场景|','|---|---:|---:|---:|---:|']
 for p in policies:
  r=a.loc[a.role.eq(role)&a.policy.eq(p)&a.scenario.eq('base')].iloc[0]
  rows.append(f'|{p} {name(p)}|{r.mean_return*100:+.2f}%|{r.mean_drawdown*100:.2f}%|{r.pooled_natural_win_rate*100:.2f}%|{int(r.zero_trade_cases)}/{int(r.cases)}|')
 return '\n'.join(rows)

